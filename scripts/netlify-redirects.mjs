// After `astro build`: turn Astro's i18n fallback pages (meta refresh after 2 s) into instant Netlify redirects.
// Example: /en/category/kuksoolwon/ has no English version -> 302 to /category/kuksoolwon/.
// 302, not 301: browsers must not cache it, because the English page may exist later.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const lines = [];

async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) await walk(full);
    else if (entry.name === 'index.html') {
      const html = await readFile(full, 'utf8');
      const target = /<meta http-equiv="refresh" content="\d+;url=([^"]+)"/.exec(html)?.[1];
      if (!target || target.startsWith('/404') || target.startsWith('/admin')) continue;
      const from = '/' + relative(DIST, dir).split(sep).join('/') + '/';
      // "!" forces the redirect although the fallback HTML file exists (Netlify serves files before rules otherwise).
      lines.push(`${encodeURI(from)}  ${encodeURI(decodeURI(target))}  302!`);
      lines.push(`${encodeURI(from.slice(0, -1))}  ${encodeURI(decodeURI(target))}  302!`);
    }
  }
}

await walk(DIST);

// Redirect pages are not real pages: remove them from the sitemap.
const sitemapFile = join(DIST, 'sitemap-0.xml');
const redirected = new Set(lines.map((l) => l.split(/\s+/)[0]));
try {
  const xml = await readFile(sitemapFile, 'utf8');
  let removed = 0;
  const pruned = xml.replace(/<url>\s*<loc>([^<]+)<\/loc>[\s\S]*?<\/url>/g, (block, loc) => {
    const path = encodeURI(decodeURI(new URL(loc).pathname));
    if (redirected.has(path)) { removed++; return ''; }
    return block;
  });
  await writeFile(sitemapFile, pruned);
  console.log(`[redirects] removed ${removed} redirect pages from the sitemap`);
} catch (e) {
  if (e.code !== 'ENOENT') throw e;
}
// Keep the hand-written rules from public/_redirects (old site addresses) and append the generated ones.
let manual = '';
try {
  manual = (await readFile(join(DIST, '_redirects'), 'utf8')).trimEnd() + '\n\n';
} catch (e) {
  if (e.code !== 'ENOENT') throw e;
}
const header = '# Generated by scripts/netlify-redirects.mjs. Untranslated pages fall back to German; short news forward to their entry in the list.\n';
await writeFile(join(DIST, '_redirects'), manual + header + lines.join('\n') + '\n');
console.log(`[redirects] ${lines.length / 2} redirects (untranslated pages, short news)`);
