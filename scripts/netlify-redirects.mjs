// After `astro build`: turn Astro's i18n fallback pages (meta refresh after 2 s) into instant Netlify redirects.
// Example: /en/category/kuksoolwon/ has no English version -> 302 to /category/kuksoolwon/.
// 302, not 301: browsers must not cache it, because the English page may exist later.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const lines = [];

async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) await walk(full);
    else if (entry.name === 'index.html') {
      const html = await readFile(full, 'utf8');
      const target = /<meta http-equiv="refresh" content="\d+;url=([^"]+)"/.exec(html)?.[1];
      if (!target || target.startsWith('/404') || target.startsWith('/admin')) continue;
      const from = '/' + relative(DIST, dir).split(sep).join('/') + '/';
      // "!" forces the redirect although the fallback HTML file exists (Netlify serves files before rules otherwise).
      lines.push(`${encodeURI(from)}  ${encodeURI(target)}  302!`);
      lines.push(`${encodeURI(from.slice(0, -1))}  ${encodeURI(target)}  302!`);
    }
  }
}

await walk(DIST);
const header = '# Generated by scripts/netlify-redirects.mjs. Do not edit; untranslated pages fall back to German.\n';
await writeFile(join(DIST, '_redirects'), header + lines.join('\n') + '\n');
console.log(`[redirects] ${lines.length / 2} untranslated pages -> German`);
